// Screenshots the zone bars in notes and the memory hover. Usage: node scripts/notes-shot.mjs <link file> <out dir> <light|dark>
import { chromium } from "playwright";
import { readFileSync } from "node:fs";
const [file, out, theme = "light"] = process.argv.slice(2);
const link = readFileSync(file, "utf8");
const b = await chromium.launch();
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2 });
await ctx.addInitScript((t) => localStorage.setItem("cadence.theme", t), theme);
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("pageerror:", e.message));
await page.goto("http://localhost:5173/r" + link.slice(link.indexOf("#")));
await page.waitForSelector(".tile");
await page.waitForTimeout(1200);
const shot = async (sel, name) => {
  await page.hover(sel);
  await page.waitForTimeout(300);
  const tip = await page.$(".info-tip");
  const box = await tip.boundingBox();
  await page.screenshot({ path: `${out}/${theme}-${name}.png`, clip: { x: box.x - 16, y: box.y - 16, width: box.width + 32, height: box.height + 32 } });
  await page.mouse.move(2, 2);
  await page.waitForTimeout(150);
};
await shot('button[aria-label="About frame rate"]', "note-fps");
await shot('button[aria-label="About longest frame"]', "note-longest");
await page.click('.tile:has-text("Page load")');
await page.waitForTimeout(700);
await shot('button[aria-label="About layout shift"]', "note-cls");
await shot('button[aria-label="About largest paint"]', "note-lcp");
await page.click('.tile:has-text("Memory")');
await page.waitForTimeout(700);
const spark = await page.$(".spark-wrap");
const sb = await spark.boundingBox();
await page.mouse.move(sb.x + sb.width * 0.7, sb.y + 20);
await page.waitForTimeout(300);
const card = await page.$(".tab-panel .card");
await card.screenshot({ path: `${out}/${theme}-memory-hover.png` });
await b.close();
