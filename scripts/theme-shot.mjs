// Screenshots a report in one theme, with notes open. Usage: node scripts/theme-shot.mjs <link file> <out dir> <light|dark> [phone]
import { chromium, devices } from "playwright";
import { readFileSync } from "node:fs";
const [file, out, theme, phone] = process.argv.slice(2);
const link = readFileSync(file, "utf8");
const b = await chromium.launch();
const { defaultBrowserType, ...iphone } = devices["iPhone 13"];
const ctx = await b.newContext(phone ? iphone : { viewport: { width: 1280, height: 900 }, deviceScaleFactor: 2 });
await ctx.addInitScript((t) => localStorage.setItem("cadence.theme", t), theme);
const page = await ctx.newPage();
page.on("pageerror", (e) => console.log("pageerror:", e.message));
const tag = `${phone ? "phone" : "desk"}-${theme}`;
await page.goto("http://localhost:5173/r" + link.slice(link.indexOf("#")));
await page.waitForSelector(".tile");
await page.waitForTimeout(1500);
await page.screenshot({ path: `${out}/${tag}-smooth.png`, fullPage: true });
await page.click('button[aria-label="About rating"]');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/${tag}-rating-info.png` });
await page.mouse.click(5, 5);
await page.click('.tile:has-text("Page load")');
await page.waitForTimeout(900);
await page.screenshot({ path: `${out}/${tag}-load.png`, fullPage: true });
await page.click('button[aria-label="About first paint"]');
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/${tag}-metric-info.png` });
await b.close();
